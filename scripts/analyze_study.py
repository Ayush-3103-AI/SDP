"""Operator-study analysis (T-0044, FR-025): explanation ON vs OFF, paired per participant, bootstrap 95 % CIs.

    python scripts/analyze_study.py --db reports/study/pilot.sqlite --out reports/operator_study.md
    python scripts/analyze_study.py --selftest
"""
import argparse
import random
import sqlite3
import statistics
import sys
from collections import defaultdict
from pathlib import Path

import numpy as np

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))

from xqi.config import load_causes
from xqi.study import CARDS_PER_BLOCK, TLX, TRUST

RESAMPLES, SEED = 10_000, 0
SENONER_PP = 7.7  # Senoner et al. 2024, pre-registered accuracy gain from explanations (03-landscape)
MIN_MEDIAN_S = 2.0  # docs/study_protocol.md: median decision under 2 s in either block = clicking through
METRICS = (  # key, label, scale for the table, unit
    ("accuracy", "accuracy", 100.0, "pp"),
    ("median_s", "median decision time", 1.0, "s"),
    ("tlx", "NASA-TLX raw mean (0-100)", 1.0, ""),
    ("trust", "trust mean (1-7)", 1.0, ""),
)


def correct(row: dict, no_action: set[str]) -> bool:
    """The chosen action undoes the true cause; for a cause with no setpoint action (misalignment) it is pause/stop."""
    if row["known_cause"] in no_action:
        return row["choice"] in ("pause", "stop")
    return row["choice"] in ("apply", "modify") and row["chosen_cause"] == row["known_cause"]


def load(db: str | Path) -> tuple[list[dict], list[dict]]:
    conn = sqlite3.connect(f"file:{Path(db).as_posix()}?mode=ro", uri=True)
    conn.row_factory = sqlite3.Row
    try:
        return ([dict(r) for r in conn.execute("SELECT * FROM choices ORDER BY id")],
                [dict(r) for r in conn.execute("SELECT * FROM surveys ORDER BY id")])
    finally:
        conn.close()


def per_participant(choices: list[dict], surveys: list[dict], no_action: set[str]) -> dict[int, dict[str, dict]]:
    """{participant: {condition: {accuracy, median_s, tlx, trust, cards, surveys}}}."""
    by = defaultdict(lambda: defaultdict(lambda: {"choices": [], "surveys": []}))
    for c in choices:
        by[c["participant"]][c["condition"]]["choices"].append(c)
    for s in surveys:
        by[s["participant"]][s["condition"]]["surveys"].append(s)
    out = {}
    for pid, conds in sorted(by.items()):
        out[pid] = {}
        for cond, d in conds.items():
            cs, ss = d["choices"], d["surveys"]
            out[pid][cond] = {
                "cards": len(cs), "surveys": len(ss),
                "accuracy": statistics.fmean(correct(c, no_action) for c in cs) if cs else None,
                "median_s": statistics.median(c["decision_s"] for c in cs) if cs else None,
                "tlx": statistics.fmean(s[f"tlx_{k}"] for s in ss for k in TLX) if ss else None,
                "trust": statistics.fmean(s[f"trust_{i}"] for s in ss for i in range(1, len(TRUST) + 1))
                if ss else None,
            }
    return out


def excluded(rows: dict[int, dict], manual: set[int]) -> dict[int, str]:
    """Protocol exclusion rules that the data can check, plus facilitator-noted IDs (``manual``)."""
    out = {}
    for pid, conds in rows.items():
        if pid in manual:
            out[pid] = "facilitator note (--exclude)"
        elif any(conds.get(c, {}).get("cards", 0) < CARDS_PER_BLOCK or not conds.get(c, {}).get("surveys")
                 for c in ("on", "off")):
            out[pid] = "did not finish both blocks"
        elif any(conds[c]["median_s"] < MIN_MEDIAN_S for c in ("on", "off")):
            out[pid] = f"median decision under {MIN_MEDIAN_S:g} s"
    return out


def bootstrap_ci(diffs: list[float], resamples: int = RESAMPLES, seed: int = SEED) -> tuple[float, float]:
    """Percentile 95 % CI of the mean paired difference, resampling participants."""
    d = np.asarray(diffs, float)
    idx = np.random.default_rng(seed).integers(0, len(d), (resamples, len(d)))
    lo, hi = np.percentile(d[idx].mean(axis=1), [2.5, 97.5])
    return float(lo), float(hi)


def paired(rows: dict[int, dict], keep: list[int]) -> dict[str, tuple[float, float, float]]:
    """{metric: (mean ON − OFF, CI low, CI high)} over the kept participants, in table units."""
    out = {}
    for key, _, scale, _ in METRICS:
        diffs = [scale * (rows[p]["on"][key] - rows[p]["off"][key]) for p in keep]
        out[key] = (statistics.fmean(diffs), *bootstrap_ci(diffs))
    return out


def render(rows: dict[int, dict], excl: dict[int, str], source: str) -> str:
    keep = [p for p in rows if p not in excl]
    lines = [
        "# Operator study: explanation ON vs OFF (T-0044, FR-025)",
        "",
        f"Source: `{source}`. Generated by `scripts/analyze_study.py`.",
        ("Accuracy = the chosen action undoes the true cause (pause/stop for a cause with no setpoint action, "
         "e.g. misalignment). Paired differences are ON − OFF per participant; 95 % CIs are percentile bootstrap "
         f"over participants ({RESAMPLES} resamples, seed {SEED})."),
        "",
        (f"**n = {len(keep)} participant(s) analysed** ({len(rows)} recorded, {len(excl)} excluded). "
         "This study is underpowered to claim significance: read the CIs as effect-size estimates, not tests. "
         "07-math §9 sets no threshold for it."),
        "",
    ]
    if excl:
        counts = defaultdict(list)
        for p, why in excl.items():
            counts[why].append(str(p))
        lines += ["## Exclusions", ""] + [f"- {why}: {len(ps)} (IDs {', '.join(ps)})" for why, ps in counts.items()]
        lines.append("")
    lines += ["## Per participant", "",
              "| participant | condition | cards | accuracy | median decision (s) | TLX raw | trust |",
              "|---|---|---|---|---|---|---|"]
    for p, conds in rows.items():
        for cond in ("off", "on"):
            m = conds.get(cond)
            if m is None:
                continue
            cell = [f"{m['accuracy']:.0%}" if m["accuracy"] is not None else "–"] + [
                f"{m[k]:.1f}" if m[k] is not None else "–" for k in ("median_s", "tlx", "trust")]
            mark = " (excluded)" if p in excl else ""
            lines.append(f"| {p}{mark} | {cond} | {m['cards']} | {' | '.join(cell)} |")
    lines += ["", "## Paired differences (ON − OFF)", ""]
    if not keep:
        lines += ["No participant left after exclusions: NO DATA.", ""]
        return "\n".join(lines)
    diff = paired(rows, keep)
    lines += ["| metric | mean ON − OFF | 95 % CI |", "|---|---|---|"]
    for key, label, _, unit in METRICS:
        m, lo, hi = diff[key]
        u = f" {unit}" if unit else ""
        lines.append(f"| {label} | {m:+.1f}{u} | [{lo:+.1f}, {hi:+.1f}]{u} |")
    m, lo, hi = diff["accuracy"]
    lines += ["", f"Accuracy gain {m:+.1f} pp (95 % CI [{lo:+.1f}, {hi:+.1f}] pp, n = {len(keep)}) against "
              f"Senoner et al. 2024's pre-registered **+{SENONER_PP} pp**. "
              + ("The CI excludes 0" if lo > 0 or hi < 0 else "The CI includes 0")
              + (", but with n = 1 the bootstrap CI collapses to the single difference." if len(keep) == 1 else "."),
              ""]
    return "\n".join(lines)


def selftest() -> int:
    """40 synthetic participants, planted +10 pp accuracy effect (60 % OFF → 70 % ON): the CI must exclude 0."""
    rng = random.Random(SEED)
    choices, surveys = [], []
    for pid in range(1, 41):
        for cond, p in (("off", 0.6), ("on", 0.7)):
            for pos in range(CARDS_PER_BLOCK):
                ok = rng.random() < p
                choices.append({"participant": pid, "condition": cond, "known_cause": "flow_low", "choice": "apply",
                                "chosen_cause": "flow_low" if ok else "speed_high", "decision_s": 3.0 + pos})
            surveys.append({"participant": pid, "condition": cond} | {f"tlx_{k}": 50.0 for k in TLX}
                           | {f"trust_{i}": 4 for i in range(1, len(TRUST) + 1)})
    rows = per_participant(choices, surveys, {"misalignment"})
    excl = excluded(rows, set())
    assert not excl, excl
    m, lo, hi = paired(rows, list(rows))["accuracy"]
    assert lo > 0 and lo < m < hi, (m, lo, hi)
    assert "CI excludes 0" in render(rows, excl, "selftest")
    print(f"selftest ok: accuracy {m:+.1f} pp, 95 % CI [{lo:+.1f}, {hi:+.1f}]")
    return 0


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--db", default="reports/study/pilot.sqlite")
    ap.add_argument("--causes", default="config/causes.yaml")
    ap.add_argument("--exclude", type=int, nargs="*", default=[], help="participant IDs a facilitator note excludes")
    ap.add_argument("--out", default="reports/operator_study.md")
    ap.add_argument("--selftest", action="store_true")
    a = ap.parse_args()
    if a.selftest:
        return selftest()
    # A cause with no setpoint action other than "none" (no defect) is undone by pause/stop: misalignment.
    no_action = {c for c, act in load_causes(a.causes).cause_action.items() if act is None and c != "none"}
    rows = per_participant(*load(a.db), no_action)
    text = render(rows, excluded(rows, set(a.exclude)), a.db)
    out = Path(a.out)
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text(text, encoding="utf-8")
    print(text)
    print(f"wrote {out}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
